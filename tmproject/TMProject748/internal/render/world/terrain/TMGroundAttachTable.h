// Returns the rule for a cell, or nullptr when the cell keeps its flags.
constexpr const Rule* Find(int x, int y)
{
    for (const Rule& rule : kRules)
        if (rule.x == x && rule.y == y)
            return &rule;
    return nullptr;
}
