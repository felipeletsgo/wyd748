func decrypt(msg []byte) bool {
	size := int(binaryLE16(msg[0:2]))
	if size < 4 || size > len(msg) {
		return false
	}
	key := keyWord[int(msg[2])*2]
	var encryptedSum, plainSum byte
	pos := int(key)
	for i := 4; i < size; i++ {
		encryptedSum += msg[i]
		trans := keyWord[(pos%256)*2+1]
		switch i & 3 {
		case 0:
			msg[i] -= trans << 1
		case 1:
			msg[i] += trans >> 3
		case 2:
			msg[i] -= trans << 2
		case 3:
			msg[i] += trans >> 5
		}
		plainSum += msg[i]
		pos++
	}
	return encryptedSum-plainSum == msg[3]
}

func encrypt(msg []byte, key byte) {
	size := int(binaryLE16(msg[0:2]))
	msg[2] = key
	var plainSum, encryptedSum byte
	pos := int(keyWord[int(key)*2])
	for i := 4; i < size; i++ {
		plainSum += msg[i]
		trans := keyWord[(pos%256)*2+1]
		switch i & 3 {
		case 0:
			msg[i] += trans << 1
		case 1:
			msg[i] -= trans >> 3
		case 2:
			msg[i] += trans << 2
		case 3:
			msg[i] -= trans >> 5
		}
		encryptedSum += msg[i]
		pos++
	}
	msg[3] = encryptedSum - plainSum
}

func binaryLE16(b []byte) uint16 { return uint16(b[0]) | uint16(b[1])<<8 }
